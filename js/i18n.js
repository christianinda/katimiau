function t(key){
  const lang = State.get().language || 'es';
  return (I18N[lang] && I18N[lang][key]) || (I18N.es[key]) || key;
}

function tOther(key){
  const lang = State.get().language || 'es';
  const other = lang === 'es' ? 'en' : 'es';
  return (I18N[other] && I18N[other][key]) || key;
}

function biLabel(key){
  const primary = t(key);
  const secondary = tOther(key);
  if(primary === secondary) return primary;
  return `<span class="b-primary">${primary}</span><span class="b-secondary">${secondary}</span>`;
}

function applyI18n(){
  document.documentElement.lang = State.get().language || 'es';
  document.querySelectorAll('[data-i18n]').forEach(el=>{
    el.textContent = t(el.getAttribute('data-i18n'));
  });
  document.querySelectorAll('[data-i18n-aria]').forEach(el=>{
    el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria')));
  });
  const langLabel = document.getElementById('lang-label');
  if(langLabel) langLabel.textContent = (State.get().language || 'es').toUpperCase();
}
